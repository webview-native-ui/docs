import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import fm from 'front-matter';
import markdownToHtml from 'zenn-markdown-html';
import { JSDOM } from 'jsdom';
import { format } from 'prettier';
import { PUBLISHED_DOCS_LOCALES } from '../shared/docs-locales';
import { GUIDE_CHAPTERS } from '../shared/guide-navigation';
import { localizedPublicPath } from '../projects/docs/src/app/locale-path';
import { assertReviewedDocsTranslation } from './docs-translation-review';
import { enforceGeneratedHtmlPolicy } from './html-policy';
import { preserveSourceHeadingLinks } from './localized-heading-anchors';

interface GuideContent {
  title: string;
  description: string;
  html: string;
  headings: { id: string; text: string }[];
  editUrl: string;
}

async function renderGuide(root: string, slug: string): Promise<Record<string, GuideContent>> {
  const english = await readFile(join(root, `projects/docs/src/guides/en/${slug}.md`), 'utf8');
  const guides: Record<string, GuideContent> = {};
  for (const { code } of PUBLISHED_DOCS_LOCALES) {
    const source = `projects/docs/src/guides/${code}/${slug}.md`;
    const raw = await readFile(join(root, source), 'utf8');
    if (code !== 'en') assertReviewedDocsTranslation(english, raw, source);
    const body = fm(raw).body.trim();
    const title = body.match(/^# (.+)$/m)?.[1];
    if (!title) throw new Error(`${source}: title is required`);
    const content = body.replace(/^# .+\n/, '').trim();
    const description = content.split('\n\n')[0];
    const document = new JSDOM(await markdownToHtml(content.slice(description.length).trim()))
      .window.document;
    for (const link of document.querySelectorAll('a[href]')) {
      const href = link.getAttribute('href')!;
      if (href.startsWith('#')) {
        const path = slug === 'standard-setup' ? '/standard-setup' : `/guides/${slug}`;
        link.setAttribute('href', `${localizedPublicPath(code, path)}${href}`);
      } else if (href.startsWith('/') && !href.startsWith('//')) {
        link.setAttribute('href', localizedPublicPath(code, href));
      }
    }
    let html = enforceGeneratedHtmlPolicy(document.body.innerHTML, source);
    if (code !== 'en') html = preserveSourceHeadingLinks(guides.en.html, html, source);
    guides[code] = {
      title,
      description,
      html,
      headings: Array.from(JSDOM.fragment(html).querySelectorAll('h2[id]')).map((heading) => ({
        id: heading.id,
        text: heading.textContent?.trim() ?? '',
      })),
      editUrl: `https://github.com/webview-native-ui/docs/edit/main/${source}`,
    };
  }
  return guides;
}

/** Setup and task tutorials belong to the portal rather than any single package. */
export async function generateStandardSetup(root: string) {
  const setup = await renderGuide(root, 'standard-setup');
  const chapters: Record<string, Record<string, GuideContent>> = {};
  for (const chapter of GUIDE_CHAPTERS) {
    const rendered = await renderGuide(root, chapter.id);
    for (const { code } of PUBLISHED_DOCS_LOCALES) {
      if (rendered[code].title !== chapter.title[code])
        throw new Error(`guides/${code}/${chapter.id}: title must match navigation`);
    }
    chapters[chapter.id] = rendered;
  }
  for (const [file, name, content] of [
    ['standard-setup.generated.ts', 'STANDARD_SETUP', setup],
    ['guide-content.generated.ts', 'GUIDE_CONTENT', chapters],
  ] as const) {
    await writeFile(
      join(root, 'projects/docs/src/app/generated', file),
      await format(
        `// Generated by scripts/generate-docs.ts. Do not edit.\nexport const ${name} = ${JSON.stringify(content)} as const;\n`,
        { parser: 'typescript', singleQuote: true, printWidth: 100 },
      ),
    );
  }
}
