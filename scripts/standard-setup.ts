import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import fm from 'front-matter';
import markdownToHtml from 'zenn-markdown-html';
import { JSDOM } from 'jsdom';
import { format } from 'prettier';
import { PUBLISHED_DOCS_LOCALES } from '../shared/docs-locales';
import { localizedPublicPath } from '../projects/docs/src/app/locale-path';
import { assertReviewedDocsTranslation } from './docs-translation-review';
import { enforceGeneratedHtmlPolicy } from './html-policy';
import { preserveSourceHeadingLinks } from './localized-heading-anchors';

/** The cross-package standard setup belongs to this portal, not an npm package. */
export async function generateStandardSetup(root: string) {
  const english = await readFile(
    join(root, 'projects/docs/src/guides/en/standard-setup.md'),
    'utf8',
  );
  const guides: Record<
    string,
    { title: string; description: string; html: string; editUrl: string }
  > = {};
  for (const { code } of PUBLISHED_DOCS_LOCALES) {
    const source = `projects/docs/src/guides/${code}/standard-setup.md`;
    const raw = await readFile(join(root, source), 'utf8');
    if (code !== 'en') assertReviewedDocsTranslation(english, raw, source);
    const body = fm(raw).body.trim();
    const title = body.match(/^# (.+)$/m)?.[1];
    if (!title) throw new Error(`${source}: title is required`);
    const content = body.replace(/^# .+\n/, '').trim();
    const description = content.split('\n\n')[0];
    const document = new JSDOM(await markdownToHtml(content)).window.document;
    for (const link of document.querySelectorAll('a[href]')) {
      const href = link.getAttribute('href')!;
      if (href.startsWith('/') && !href.startsWith('//')) {
        link.setAttribute('href', localizedPublicPath(code, href));
      }
    }
    let html = enforceGeneratedHtmlPolicy(document.body.innerHTML, source);
    if (code !== 'en') html = preserveSourceHeadingLinks(guides.en.html, html, source);
    guides[code] = {
      title,
      description,
      html,
      editUrl: `https://github.com/webview-native-ui/docs/edit/main/${source}`,
    };
  }
  await writeFile(
    join(root, 'projects/docs/src/app/generated/standard-setup.generated.ts'),
    await format(
      `// Generated by scripts/generate-docs.ts. Do not edit.\nexport const STANDARD_SETUP = ${JSON.stringify(guides)} as const;\n`,
      { parser: 'typescript', singleQuote: true, printWidth: 100 },
    ),
  );
}
